"""Build a pad-size variant from the A5 source: same content, size-specific layout overrides.

usage: python3 build/make-variant.py 4.5x7
Writes prescription-pad-4.5x7.html next to prescription-pad.html (the A5 source stays the only place
product content is edited). Then: node build/render.js <tmp-dir> 4.5x7
"""
import os
import sys

SIZES = {'4.5x7': {'w': '114.3', 'h': '177.8', 'label': '4.5 &times; 7 in', 'cls': 's45'}}
key = sys.argv[1]
v = SIZES[key]
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = open(os.path.join(here, 'prescription-pad.html'), encoding='utf-8').read()
css = open(os.path.join(here, 'build', f'size-{key}.css'), encoding='utf-8').read()
src = src.replace('<html lang="en">',
                  f'<html lang="en" class="{v["cls"]}" data-w="{v["w"]}" data-h="{v["h"]}" data-size="{v["label"]}">', 1)
src = src.replace('<title>IDMA Prescription Pad Sample</title>', f'<title>IDMA Rx Pad {key}</title>', 1)
src = src.replace('</head>', f'<style id="size-{key}">\n{css}</style>\n<!-- GENERATED by build/make-variant.py {key}: edit prescription-pad.html or build/size-{key}.css, not this file -->\n</head>', 1)
out = os.path.join(here, f'prescription-pad-{key}.html')
open(out, 'w', encoding='utf-8').write(src)
print('wrote', out)
